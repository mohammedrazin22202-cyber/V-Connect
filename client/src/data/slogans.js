/**
 * Calculates the deterministic slogan index based on the current hour.
 * Updates precisely at the top of every hour (00:00).
 * 
 * @param {Date} [date=new Date()]
 * @returns {number} Index between 0 and SLOGANS.length - 1
 */
export function getHourlySloganIndex(date = new Date()) {
  // Milliseconds since epoch divided by 1 hour (3,600,000 ms)
  const hourEpoch = Math.floor(date.getTime() / (1000 * 60 * 60));
  return Math.abs(hourEpoch) % RURAL_SLOGANS.length;
}

/**
 * Returns the slogan for the current hour.
 * 
 * @param {Date} [date=new Date()]
 * @returns {string} Slogan text
 */
export function getHourlySlogan(date = new Date()) {
  const idx = getHourlySloganIndex(date);
  return RURAL_SLOGANS[idx];
}

/**
 * Returns the milliseconds remaining until the next exact hour rollover.
 * 
 * @param {Date} [date=new Date()]
 * @returns {number} Milliseconds until next hour (e.g. 10:00:00)
 */
export function getMsUntilNextHour(date = new Date()) {
  const ONE_HOUR = 60 * 60 * 1000;
  const ms = date.getTime();
  const remainder = ms % ONE_HOUR;
  return remainder === 0 ? ONE_HOUR : ONE_HOUR - remainder;
}

